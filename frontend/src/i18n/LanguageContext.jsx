const roles = {
  tr: { ADMIN: 'Yönetici', TECHNICIAN: 'Teknisyen', CUSTOMER: 'Müşteri' },
  en: { ADMIN: 'Admin', TECHNICIAN: 'Technician', CUSTOMER: 'Customer' }
}

const priorities = {
  tr: { LOW: 'Düşük', MEDIUM: 'Orta', HIGH: 'Yüksek', URGENT: 'Acil' },
  en: { LOW: 'Low', MEDIUM: 'Medium', HIGH: 'High', URGENT: 'Urgent' }
}

function interpolate(value, values = {}) {
  return Object.entries(values).reduce((text, [key, replacement]) => text.replaceAll(`{${key}}`, replacement ?? ''), value)
}

export function translate(key, language = 'en', values) {
  const value = language === 'tr' ? (turkish[key] || key) : key
  return interpolate(value, values)
}

export function formatDate(value, language = 'en', withTime = false) {
  if (!value) return ''
  const locale = language === 'tr' ? 'tr-TR' : 'en-US'
  return withTime ? new Date(value).toLocaleString(locale) : new Date(value).toLocaleDateString(locale)
}

export function formatMoney(value, language = 'en') {
  return new Intl.NumberFormat(language === 'tr' ? 'tr-TR' : 'en-US', { style: 'currency', currency: 'TRY' }).format(value)
}

const fallbackContext = {
  language: 'en',
  setLanguage: () => {},
  t: (key, values) => translate(key, 'en', values),
  statusLabel: (value) => statuses.en[value] || value?.replaceAll('_', ' '),
  roleLabel: (value) => roles.en[value] || value,
  priorityLabel: (value) => priorities.en[value] || value
}

const LanguageContext = createContext(fallbackContext)

export function LanguageProvider({ children, initialLanguage }) {
  const [language, setLanguage] = useState(() => initialLanguage || localStorage.getItem(STORAGE_KEY) || 'tr')

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key, values) => translate(key, language, values),
    statusLabel: (status) => statuses[language]?.[status] || status?.replaceAll('_', ' '),
    roleLabel: (role) => roles[language]?.[role] || role,
    priorityLabel: (priority) => priorities[language]?.[priority] || priority
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}
